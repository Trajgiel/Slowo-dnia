// One-off transfer of the course data from the prototype (architecture/react-port/course-data.md
// in the workspace, "Перенос данных и проверка").
//
//   node scripts/extract-courses.ts <prototype-dir>
//
// <prototype-dir> holds the prototype's index.html (W, BOY, BOY_THEME) and courses/adult.js
// (in the workspace: materials/project). The script writes:
// - src/data/kidsCourse.ts — the kids course, BOY and BOY_THEME as a typed module;
// - src/data/adult.json — the adult course, loaded by src/data/loadCourse.ts;
// - src/test/fixtures/prototype-courses.json — the prototype data untouched, for the comparison test.
// The only change of the data: three kids translations without the long dash
// (decisions/product/2026-10-25-no-long-dash.md; texts — content/ui/kids-course-data.md).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { runInNewContext } from 'node:vm'
import { format, resolveConfig } from 'prettier'

type Form = [string, string, string]
type Theme = [string, unknown[][]]

interface PrototypeCourses {
  kids: Theme[]
  boy: Record<string, Form>
  boyTheme: Record<string, string>
  adult: Theme[]
}

/** Kids translations rewritten by content: word index (from 0) → prototype text and new text. */
const KIDS_TRANSLATION_EDITS: readonly { index: number; from: string; to: string }[] = [
  { index: 41, from: 'Мой любимый цвет —…', to: 'Мой любимый цвет…' },
  {
    index: 240,
    from: '«Сто лет!» — песенка-поздравление',
    to: 'Сто лет! (песенка-поздравление)',
  },
  { index: 275, from: 'Раз, два, три — ищу!', to: 'Раз, два, три, ищу!' },
]

const root = fileURLToPath(new URL('..', import.meta.url))

function fail(message: string): never {
  console.error(`extract-courses: ${message}`)
  process.exit(1)
}

/** Plain data out of another VM realm. */
function plain(value: unknown): unknown {
  return JSON.parse(JSON.stringify(value))
}

function readPrototype(dir: string): PrototypeCourses {
  const html = readFileSync(join(dir, 'index.html'), 'utf8')
  const start = html.indexOf('const W = [')
  const themeDecl = html.indexOf('const BOY_THEME=', start)
  const end = html.indexOf(';', themeDecl)
  if (start < 0 || themeDecl < 0 || end < 0) fail('W … BOY_THEME not found in index.html')
  const source = html.slice(start, end + 1)
  const kids = plain(
    runInNewContext(`${source}\n;({ kids: W, boy: BOY, boyTheme: BOY_THEME })`),
  ) as Omit<PrototypeCourses, 'adult'>

  const sandbox: { window: { COURSE_ADULT?: unknown } } = { window: {} }
  runInNewContext(readFileSync(join(dir, 'courses', 'adult.js'), 'utf8'), sandbox)
  if (!Array.isArray(sandbox.window.COURSE_ADULT)) fail('window.COURSE_ADULT not set by adult.js')
  return { ...kids, adult: plain(sandbox.window.COURSE_ADULT) as Theme[] }
}

function withEdits(kids: Theme[]): Theme[] {
  const edited = plain(kids) as Theme[]
  const entries = edited.flatMap(([, items]) => items)
  for (const { index, from, to } of KIDS_TRANSLATION_EDITS) {
    const entry = entries[index]
    if (entry?.[1] !== from) fail(`kids word ${String(index)}: expected ru "${from}"`)
    entry[1] = to
  }
  const left = entries.find((entry) => String(entry[1]).includes('—'))
  if (left) fail(`kids translation with a long dash left: ${String(left[1])}`)
  return edited
}

async function write(path: string, text: string): Promise<void> {
  const file = join(root, path)
  const options = await resolveConfig(file)
  writeFileSync(file, await format(text, { ...options, filepath: file }))
  console.log(`wrote ${path}`)
}

const prototypeDir = process.argv[2]
if (!prototypeDir) fail('usage: node scripts/extract-courses.ts <prototype-dir>')
const prototype = readPrototype(prototypeDir)
const kids = withEdits(prototype.kids)

await write(
  'src/data/kidsCourse.ts',
  `// Generated by scripts/extract-courses.ts from the prototype; do not edit by hand.
// Kids course: the base form is the girl's; masculine forms are in KIDS_BOY.
import type { KidsBoyForms, KidsCourseData } from '../domain'

export const KIDS_THEMES: KidsCourseData = ${JSON.stringify(kids)}

export const KIDS_BOY: KidsBoyForms = ${JSON.stringify({ words: prototype.boy, themes: prototype.boyTheme })}
`,
)
await write('src/data/adult.json', JSON.stringify(prototype.adult))
await write('src/test/fixtures/prototype-courses.json', JSON.stringify(prototype))
